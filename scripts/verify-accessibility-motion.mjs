import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const baseUrl = process.env.PLAYWRIGHT_BASE_URL || 'http://127.0.0.1:3000';
const browser = await chromium.launch({channel:'chrome',headless:true});
try {
  const page = await browser.newPage({viewport:{width:390,height:844}});
  await page.goto(`${baseUrl}/contact`);
  await page.waitForTimeout(1200);
  await page.getByRole('button',{name:'Open menu'}).click();
  await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'About',exact:true}).focus();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('button',{name:'Open menu'}).evaluate(e=>e===document.activeElement),true);
  await page.getByLabel('Mobile',{exact:true}).fill('not-a-number');
  assert.equal(await page.getByLabel('Mobile',{exact:true}).evaluate(e=>e.checkValidity()),false);
  await page.getByLabel('Mobile',{exact:true}).fill('+91 98765 43210');
  assert.equal(await page.getByLabel('Mobile',{exact:true}).evaluate(e=>e.checkValidity()),true);
  await page.goto(`${baseUrl}/projects/rostering`);
  const breadcrumb = page.getByRole('navigation',{name:'Breadcrumb'});
  assert.equal(await breadcrumb.getByRole('link',{name:'Projects',exact:true}).getAttribute('href'),'/projects');
  assert.equal(await breadcrumb.locator('[aria-current=page]').innerText(),'Workforce Rostering SaaS');
  await page.setViewportSize({width:1440,height:900});
  await page.goto(baseUrl);
  await page.waitForFunction(()=>{const v=document.querySelector('video');return v&& !v.paused && v.currentTime>0;});
  await page.getByRole('button',{name:'Pause motion'}).click();
  await page.waitForFunction(()=>document.querySelector('video').paused && document.documentElement.dataset.userMotion==='paused' && !document.documentElement.dataset.motion);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.emulateMedia({reducedMotion:'no-preference'});
  assert.equal(await page.locator('video').evaluate(v=>v.paused),true,'User pause must survive preference changes');
  await page.getByRole('button',{name:'Resume motion'}).click();
  await page.waitForFunction(()=>!document.querySelector('video').paused);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.waitForFunction(()=>document.querySelector('video').paused);
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.waitForFunction(()=>!document.querySelector('video').paused);
  await page.locator('.contact-form').evaluate(e=>e.scrollIntoView({block:'center',behavior:'instant'}));
  await page.waitForTimeout(1200);
  await page.locator('.contact-form').hover();
  await page.waitForTimeout(300);
  assert.equal(await page.locator('.contact-form').evaluate(e=>getComputedStyle(e).scale),'1');
  console.log('PASS menu focus, phone validation, breadcrumbs, user pause, preference resume, stable form');
  const touch = await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  await touch.goto(baseUrl);
  await touch.waitForFunction(()=>document.documentElement.classList.contains('touch-motion'));
  await touch.locator('.project-card').first().scrollIntoViewIfNeeded();
  await touch.waitForFunction(()=>getComputedStyle(document.querySelector('.project-card')).opacity==='1');
  await touch.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await touch.getByRole('button',{name:'Pause motion'}).click();
  await touch.waitForFunction(()=>!document.documentElement.dataset.motion);
  assert.equal(await touch.locator('.motion-reveal-pending').count(),0);
  await touch.getByRole('button',{name:'Resume motion'}).click();
  await touch.waitForFunction(()=>document.documentElement.classList.contains('touch-motion'));
  await touch.emulateMedia({reducedMotion:'reduce'});
  await touch.waitForFunction(()=>!document.documentElement.dataset.motion);
  console.log('PASS native touch reveal, user pause cleanup, and reduced-motion cleanup');
} finally { await browser.close(); }
